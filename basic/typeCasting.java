package basic;

public class typeCasting {
    static void main(String[] args) {
        // int / int = int

        System.out.println(  5/2);

        // double / int = double

        System.out.println(5.0/2);

        // int /double = doulble

        System.out.println(5/2.0);

        // double / bouble  = double

        System.out.println(5.0/2.0);

    }
}
